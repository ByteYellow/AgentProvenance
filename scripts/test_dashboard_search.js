// Browser checks against the explicitly synthetic ui-search fixture.
async (page) => {
  const checks=[],errors=[];
  const check=(value,label)=>{if(!value)throw new Error(label);checks.push(label);};
  const base=new URL(await page.url()).origin;
  page=await page.context().newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto(base+'/?run=ui-search&harness=codex&session=search-main&lang=en&live=0&detail=raw');
  await page.waitForFunction(()=>window._lensManifest?.query.session_scope?.session_id==='search-main');
  await page.locator('#zoomin').click();
  const original=await page.evaluate(()=>JSON.stringify({LENS,DETAIL,SEL,ZOOM,FIT,SESSION_SCOPE}));
  async function search(query,category=''){
    await page.locator('#search-query').fill(query);
    await page.locator('#search-category').selectOption(category);
    await page.locator('#search-submit').click();
    await page.waitForFunction(()=>!document.querySelector('#search-submit').disabled);
  }
  await page.locator('[data-investigation="search"]').click();
  check(await page.locator('#search-scope').inputValue()==='session','search defaults to the selected native session');
  await search('permission denied','tools');
  check(await page.locator('.search-result').count()===1,'same saved output is grouped without losing source references');
  check(await page.locator('.search-result').innerText().then(s=>s.includes('2 source references')),'both saved sources are available');
  check(await page.locator('.search-result').innerText().then(s=>s.includes('truncated')),'source-reported truncation stays visible on the hit');
  await page.waitForFunction(()=>document.querySelector('#content-body')?.textContent.includes('permission denied'));
  check(await page.evaluate(()=>AgentContextUI.readerPosition().offset>131072 && document.querySelector('#content-body').textContent.startsWith('permission denied')),'long-body hit opens at its saved byte offset');
  check(await page.locator('#content-prev').isEnabled(),'the hit keeps a route back to the beginning of the saved body');
  check(await page.locator('#content-body mark').count()>0,'the shared reader highlights literal matches');
  check(await page.locator('#content-body img').count()===0,'evidence HTML is not executed');
  check(await page.locator('#search-source option').count()===2,'duplicate references can be inspected separately');
  await page.locator('#search-raw').click();
  await page.waitForFunction(()=>document.querySelector('#content-body')?.textContent.includes('"fixture":true'));
  await page.locator('#search-close').click();
  await page.locator('[data-investigation="search"]').click();
  await page.waitForFunction(()=>document.querySelector('#content-body')?.textContent.includes('"fixture":true'));
  check(await page.locator('#content-choice').inputValue()==='1','reopening retains the raw-source selection');
  await page.locator('.search-result').click();
  await page.waitForSelector('#search-links button');
  await page.locator('#search-links button').first().click();
  await page.locator('#search-dialog').waitFor({state:'hidden'});
  await page.locator('#search-return').waitFor();
  check(await page.evaluate(()=>SEL?.startsWith('context-tool-')),'search follows an existing tool relationship');
  await page.locator('#search-return').click();
  await page.locator('#search-dialog').waitFor();
  check(await page.locator('#search-query').inputValue()==='permission denied','return retains the keyword');
  check(await page.locator('.search-result').count()===1,'return retains the matching page');
  check(await page.evaluate(()=>JSON.stringify({LENS,DETAIL,SEL,ZOOM,FIT,SESSION_SCOPE}))===original,'return restores the original graph and session scope');
  await search('OTHER-SESSION-ONLY');
  check(await page.locator('.search-result').count()===0,'another session is excluded');
  check(await page.locator('#search-status').innerText()==='No match found in saved content.','empty result names the saved-content scope');
  await page.locator('#search-scope').selectOption('run');
  await search('OTHER-SESSION-ONLY');
  check(await page.locator('.search-result').count()===1,'explicit whole-run search can find another session');
  await search('saved-report.txt','files');
  check(await page.locator('.search-result').count()===1,'a saved filename is searchable');
  check(await page.locator('.search-result').innerText().then(s=>s.includes('Source field match')),'metadata matches are distinguished from body matches');
  await page.waitForFunction(()=>document.querySelector('#content-body')?.textContent.includes('UNASSIGNED-FILE-ONLY'));
  await page.locator('#search-scope').selectOption('session');
  await search('UNASSIGNED-FILE-ONLY','files');
  check(await page.locator('.search-result').count()===0,'unassigned saved files are not added by sharing a run');
  await search('permission denied');
  check(await page.locator('#search-counts').innerText().then(s=>s.includes('2 bodies unavailable')),'missing bodies are reported separately');
  await page.locator('#search-close').click();
  await page.waitForSelector('#content-home > #content-pane',{state:'attached'});
  check(await page.locator('#content-home > #content-pane').count()===1,'close restores the original reader container');
  await page.locator('[data-investigation="search"]').click();
  check(await page.locator('#search-query').inputValue()==='permission denied','reopen retains query');
  await page.waitForFunction(()=>document.querySelector('#content-body')?.textContent.includes('permission denied'));
  await page.screenshot({path:'output/playwright/search-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile document has no horizontal overflow');
  check(await page.locator('#search-dialog').evaluate(e=>e.scrollWidth<=e.clientWidth+1),'mobile search dialog has no horizontal overflow');
  check(await page.locator('#content-body').evaluate(e=>getComputedStyle(e).overflowY==='auto'),'long text scrolls independently');
  await page.screenshot({path:'output/playwright/search-mobile.png'});
  let release,received,waiting=true;
  const pending=new Promise(r=>release=r),arrived=new Promise(r=>received=r);
  await page.route('**/api/context/content?**',async route=>{if(waiting){waiting=false;received();await pending;}await route.continue().catch(()=>{});});
  await page.locator('#search-query').fill('missing-search-token');
  await page.locator('#search-submit').click();await arrived;
  await page.locator('#search-stop').click();
  await page.waitForFunction(()=>!document.querySelector('#search-submit').disabled);
  check(await page.locator('#search-status').innerText().then(s=>s.includes('Search stopped')),'cancel reports the unsearched remainder');
  release();await page.unroute('**/api/context/content?**');
  await page.locator('#search-more').click();
  await page.waitForFunction(()=>!document.querySelector('#search-submit').disabled);
  check(await page.locator('#search-status').innerText()==='No match found in saved content.','search can resume after cancellation');
  await search('permission denied','tools');
  check(await page.locator('#search-status').innerText().then(s=>s.includes('matching records')),'a new search clears the previous cancellation state');
  await page.locator('#search-close').click();
  await page.getByRole('link',{name:'中文',exact:true}).click();
  await page.waitForFunction(()=>window._lensManifest);
  await page.locator('[data-investigation="search"]').click();
  await search('permission denied','tools');
  check(await page.locator('#search-status').innerText().then(s=>s.includes('命中记录')),'search results are localized');
  check(errors.length===0,'no unhandled browser errors: '+errors.join('; '));
  await page.close();
  return {fixture:'synthetic saved search evidence; no historical capture modified',checks:checks.length,passed:checks};
}
