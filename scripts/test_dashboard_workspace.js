// Run with playwright-cli against TestContextDashboardFixture's local server.
// Session relations here are synthetic fixtures, not historical demo evidence.
async (page) => {
  const checks = [], errors = [];
  const check = (ok,name) => { if (!ok) throw new Error(name); checks.push(name); };
  const base = await page.evaluate(()=>location.origin);
  page = await page.context().newPage();
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto(base+'/?run=ui-sessions&lang=en&live=0');
  await page.waitForFunction(()=>document.querySelector('#session-count')?.textContent==='3');
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-sessions');
  check(await page.locator('#inspection').isHidden(),'empty reader is hidden');
  check(await page.locator('.auxiliary-fold[open]').count()===0,'auxiliary sections start collapsed');
  check(await page.locator('#runoverview [data-investigation]').count()===3,'three investigation entries stay in the overview');
  await page.locator('[data-investigation="search"]').click();
  check(await page.locator('#search-dialog').isVisible(),'search opens the shared temporary investigation window');
  await page.locator('#search-close').click();
  await page.waitForSelector('#content-home > #content-pane',{state:'attached'});
  for (const action of ['compare','export']) {
    await page.locator('[data-investigation="'+action+'"]').click();
    check(await page.locator('#investigation-dialog').innerText().then(s=>s.includes('not available in this build')),'unfinished action is explicit: '+action);
    await page.locator('#investigation-close').click();
  }
  check(await page.locator('#session-members button[data-session-index]').count()===3,'three native sessions, not one per source');
  const graph = await page.evaluate(()=>JSON.stringify(window._lg));
  await page.locator('#session-directory-open').click();
  check(await page.locator('#session-directory').evaluate(el=>el.open),'session directory opens');
  const worker = page.locator('.session-item').filter({has:page.locator('h3').filter({hasText:/^worker/})});
  check(await worker.locator('[data-session-source]').count()===2,'session preserves transcript and hooks sources');
  await worker.locator('[data-parent-session]').click();
  check(await page.evaluate(()=>document.activeElement?.querySelector('h3')?.textContent.startsWith('root codex')),'parent link resolves within the harness namespace');
  check(await page.locator('#session-directory-body').innerText().then(s=>s.includes('Parent session is not in this run')),'missing parent is labeled');
  check(await page.locator('#session-directory-body').innerText().then(s=>s.includes('Sources without session identity')),'unassigned source stays inspectable');
  check(!await page.locator('#session-directory-body').innerText().then(s=>s.includes('ui-sessions launch')),'processing diagnostics are not native sessions');
  await page.locator('#session-directory-close').click();
  await page.locator('[data-context-open="coverage"]').click();
  await page.locator('[data-processing-coverage] details > summary').click();
  const processing = JSON.parse(await page.locator('[data-processing-coverage] pre').innerText());
  const overview = await (await page.request.get(base+'/api/context/overview?run=ui-sessions')).json();
  check(JSON.stringify(processing)===JSON.stringify(overview.coverage.find(report=>report.source.channel==='processing')),'processing diagnostics retain their full source metadata');
  await page.locator('#session-directory-open').click();
  await page.screenshot({path:'output/playwright/workspace-sessions-desktop.png'});
  const source = await worker.locator('[data-session-source]').first().getAttribute('data-session-source');
  await worker.locator('[data-session-source]').first().click();
  await page.waitForSelector('#context-body [data-entry]');
  check(await page.locator('#context-source').inputValue()===source,'source selection uses its exact stored ID');
  check(await page.locator('#context-body [data-entry]').count()===1,'source filter includes only its saved record');
  check(await page.evaluate(()=>JSON.stringify(window._lg))===graph,'source selection preserves run-wide graph');
  await page.locator('#context-body [data-entry]').getByRole('button',{name:'Open saved content',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#content-body')?.textContent.includes('Synthetic session directory fixture'));
  check(await page.locator('#savedcontent').isVisible() && await page.locator('#detail').isHidden(),'one reader pane visible at a time');
  await page.locator('#session-directory-open').click();
  await page.setViewportSize({width:390,height:844});
  check(await page.locator('#session-directory').evaluate(el=>el.getBoundingClientRect().width<=innerWidth),'mobile session directory fits');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile page has no horizontal overflow');
  await page.screenshot({path:'output/playwright/workspace-sessions-mobile.png'});
  await page.locator('#session-directory-close').click();
  check(await page.locator('#content-body').innerText().then(s=>s.includes('Synthetic session directory fixture')),'closing directory preserves content');
  await page.locator('#runsel').selectOption('ui-fixture');
  await page.waitForFunction(()=>document.querySelector('#session-count')?.textContent==='1');
  check(await page.locator('#inspection').isHidden(),'switching runs clears previous evidence reader');
  await page.setViewportSize({width:1440,height:1050});
  await page.locator('[data-context-open="conversation"]').first().click();
  await page.waitForSelector('#context-body [data-entry]');
  const call = page.locator('#context-body [data-entry]').filter({hasText:'Tool input'}).first();
  await call.getByRole('button',{name:'Locate in graph',exact:true}).click();
  await page.locator('#detail-session').waitFor();
  check(await page.locator('#inspection-tab-summary').getAttribute('aria-selected')==='true','graph navigation opens summary');
  check(!await page.locator('#detail > details').evaluate(el=>el.open),'technical fields start folded');
  await page.locator('#inspection-tab-content').click();
  check(await page.locator('#detail').isHidden(),'content reading hides the summary');
  await page.locator('#content-expand').click();
  await page.keyboard.press('Escape');
  await page.waitForSelector('#content-home #content-pane',{state:'attached'});
  check(await page.locator('#content-home #content-pane').count()===1,'Escape returns the same content element');
  await page.locator('#inspection-close').click();
  check(await page.locator('#inspection').isHidden(),'reader can be dismissed');
  await page.evaluate(()=>loadRun(cur));
  check(await page.locator('#inspection').isHidden(),'refresh does not reopen dismissed reader');
  await page.locator('#context-nav-files').click();
  check(await page.locator('#savedcontent').isVisible(),'file shortcut reopens reader');
  await page.getByRole('link',{name:'中文',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#session-count')?.textContent==='1');
  check(await page.locator('#inspection-tab-content').getAttribute('aria-selected')==='true','language switch retains active reader pane');
  await page.locator('#session-directory-open').click();
  check(await page.locator('#session-directory-title').innerText()==='会话与来源','session directory is localized');
  await page.locator('#session-directory-close').click();
  check(errors.length===0,'no unhandled browser errors: '+errors.join('; '));
  await page.close();
  return {source:'synthetic session fixtures',checks:checks.length,passed:checks};
}
