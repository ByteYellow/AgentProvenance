// Browser checks against the explicitly synthetic paired-run fixtures.
async (page) => {
  const checks=[],errors=[];
  const check=(value,label)=>{if(!value)throw new Error(label);checks.push(label);};
  const base=new URL(await page.url()).origin;
  page=await page.context().newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto(base+'/?run=ui-compare-a&harness=codex&session=compare-a&lang=en&live=0&detail=raw');
  await page.waitForFunction(()=>window._lensManifest?.query.session_scope?.session_id==='compare-a');
  await page.locator('#zoomin').click();
  const original=await page.evaluate(()=>JSON.stringify({cur,LENS,DETAIL,SEL,ZOOM,FIT,SESSION_SCOPE}));
  await page.locator('[data-investigation="compare"]').click();
  await page.waitForFunction(()=>document.querySelector('#compare-a').value==='ui-compare-a');
  check(await page.locator('#compare-b').inputValue()==='','B requires an explicit selection');
  check(await page.locator('#compare-scope-note').innerText().then(s=>s.includes('whole runs')),'whole-run scope stays visible');
  await page.locator('#compare-b').selectOption('ui-compare-b');
  await page.waitForFunction(()=>document.querySelector('#compare-status').textContent==='Saved records loaded'&&!document.querySelector('#compare-refresh').disabled);
  check(await page.locator('#compare-task-note').innerText().then(s=>s.includes('texts match')),'matching recorded tasks are identified');
  check(await page.locator('#compare-task-a').innerText().then(s=>s.includes('synthetic fixture')),'the recorded task is readable');
  check(await page.locator('#compare-task-b').innerText().then(s=>s.includes('synthetic fixture')),'both task headers load');
  check(await page.locator('.compare-row').count()===3,'model, network flag and missing null field differ');
  check(await page.locator('.compare-row').filter({hasText:'/permissions'}).innerText().then(s=>s.includes('Only A recorded')),'missing configuration is not treated as denied or null');
  check(!await page.locator('#compare-results').innerText().then(s=>s.includes('past_only')),'prior context is excluded from execution comparison');
  const model=page.locator('.compare-row').filter({hasText:'codex · /model'});
  await model.locator('summary').click();
  check(await model.locator('.compare-side').nth(0).innerText().then(s=>s.includes('"fixture-model"')),'A field value is visible');
  check(await model.locator('.compare-side').nth(1).innerText().then(s=>s.includes('"fixture-model-b"')),'B field value is visible');
  await model.locator('[data-record-read]').nth(1).click();
  await page.waitForFunction(()=>document.querySelector('#content-body').textContent.includes('"fixture-model-b"'));
  check(await page.locator('#compare-reader-title').innerText().then(s=>s.startsWith('ui-compare-b')),'shared reader uses B, not the current dashboard run');
  await page.locator('#content-choice').selectOption('1');
  await page.waitForFunction(()=>document.querySelector('#content-body').textContent.includes('"network_access":true'));
  await page.locator('#compare-reader-close').click();
  await model.locator('[data-record-read]').nth(1).click();
  check(await page.locator('#content-choice').inputValue()==='1','reader retains the raw-source selection');
  await page.locator('#compare-reader-close').click();
  await page.locator('#compare-only').uncheck();
  check(await page.locator('.compare-row').count()===5,'common fields can be expanded on demand');
  check(await page.locator('.compare-row').filter({hasText:'/large_number'}).innerText().then(s=>s.includes('Common recorded values')),'large integers keep their exact equality');
  await page.locator('#compare-only').check();
  await page.locator('#compare-swap').click();
  await page.waitForFunction(()=>!document.querySelector('#compare-refresh').disabled);
  check(await page.locator('#compare-a').inputValue()==='ui-compare-b','swap changes the baseline');
  check(await page.locator('.compare-row').filter({hasText:'/permissions'}).innerText().then(s=>s.includes('Only B recorded')),'swap reverses one-sided evidence');
  await page.locator('#compare-swap').click();
  await page.waitForFunction(()=>!document.querySelector('#compare-refresh').disabled);
  await page.locator('[data-dimension="files"]').click();
  const file=page.locator('.compare-row').filter({hasText:'Saved file version'});
  await file.locator('summary').click();
  await file.locator('[data-record-read]').nth(1).click();
  await page.waitForFunction(()=>document.querySelector('#content-body').textContent.includes('Synthetic file b'));
  check(await page.locator('#content-body img').count()===0,'saved HTML stays text');
  await page.locator('#compare-reader-close').click();
  await page.locator('[data-dimension="network"]').click();
  const extra=page.locator('.compare-row').filter({hasText:'api.mixpanel.com/track'});
  await extra.locator('summary').click();
  check(await extra.innerText().then(s=>s.includes('Only B recorded')),'one-sided destination remains a record comparison');
  await extra.locator('[data-record-graph]').click();
  await extra.locator('.context-notice button').click();
  await page.locator('#compare-dialog').waitFor({state:'hidden'});
  await page.locator('#compare-return').waitFor();
  check(await page.evaluate(()=>cur==='ui-compare-b'&&SEL==='runtime_event/ui-compare-b-extra'&&!SESSION_SCOPE),'graph link opens the recorded B event without A session filter');
  await page.locator('#compare-return').click();
  await page.waitForFunction(()=>document.querySelector('#compare-dialog').open);
  check(await page.evaluate(()=>JSON.stringify({cur,LENS,DETAIL,SEL,ZOOM,FIT,SESSION_SCOPE}))===original,'return restores original run, scope, lens, selection and zoom');
  check(await page.locator('[data-dimension="network"]').getAttribute('aria-pressed')==='true','comparison dimension is retained');
  check(await page.locator('.compare-row[open]').count()>=1,'expanded comparison evidence is retained');
  await page.locator('[data-dimension="outbound"]').click();
  check(await page.locator('.compare-row').filter({hasText:'api.mixpanel.com/track'}).count()===1,'outbound categories use saved evidence');
  await page.locator('.compare-row').first().locator('summary').click();
  await page.screenshot({path:'output/playwright/compare-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile document has no horizontal overflow');
  check(await page.locator('#compare-dialog').evaluate(e=>e.scrollWidth<=e.clientWidth+1),'mobile comparison has no horizontal overflow');
  await page.screenshot({path:'output/playwright/compare-mobile.png'});
  await page.locator('[data-record-read]').first().click();
  await page.waitForFunction(()=>document.querySelector('#content-body').textContent.includes('mixpanel'));
  check(await page.locator('#content-body').evaluate(e=>getComputedStyle(e).overflowY==='auto'),'evidence reader scrolls independently on mobile');
  await page.locator('#compare-reader-close').click();
  await page.locator('#compare-close').click();
  check(await page.locator('#content-home > #content-pane').count()===1,'close returns the reader to the dashboard');
  await page.locator('[data-investigation="compare"]').click();
  check(await page.locator('#compare-b').inputValue()==='ui-compare-b','reopen retains the compared runs');
  let release,received,waiting=true;
  const pending=new Promise(r=>release=r),arrived=new Promise(r=>received=r);
  await page.route('**/api/compare/records?**',async route=>{if(waiting){waiting=false;received();await pending;}await route.continue().catch(()=>{});});
  await page.locator('#compare-refresh').click();await arrived;
  await page.locator('#compare-stop').click();
  await page.waitForFunction(()=>!document.querySelector('#compare-refresh').disabled);
  check(await page.locator('#compare-status').innerText().then(s=>s.includes('stopped')),'cancel reports interrupted loading');
  release();await page.unroute('**/api/compare/records?**');
  await page.locator('#compare-refresh').click();
  await page.waitForFunction(()=>!document.querySelector('#compare-refresh').disabled);
  check(await page.locator('#compare-status').innerText()==='Saved records loaded','refresh recovers after cancellation');
  await page.route('**/api/compare/records?**',route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'synthetic store outage'})}));
  await page.locator('#compare-refresh').click();
  await page.waitForFunction(()=>!document.querySelector('#compare-refresh').disabled);
  check(await page.locator('#compare-status').innerText().then(s=>s.includes('could not be loaded')),'failed reload reports an error instead of equal or empty records');
  check(await page.locator('#compare-pair').isVisible(),'failed reload retains previously loaded evidence');
  await page.unroute('**/api/compare/records?**');
  await page.locator('#compare-refresh').click();
  await page.waitForFunction(()=>!document.querySelector('#compare-refresh').disabled);
  check(await page.locator('#compare-status').innerText()==='Saved records loaded','reload recovers after a store error');
  await page.locator('#compare-b').selectOption('ui-compare-a');
  check(await page.locator('#compare-status').innerText()==='Choose two different runs.','same-run selection is explicit');
  check(await page.locator('#compare-pair').isHidden(),'same-run selection clears stale comparison');
  await page.locator('#compare-close').click();
  await page.getByRole('link',{name:'中文',exact:true}).click();
  await page.waitForFunction(()=>window._lensManifest);
  await page.locator('[data-investigation="compare"]').click();
  await page.locator('#compare-b').selectOption('ui-compare-b');
  await page.waitForFunction(()=>!document.querySelector('#compare-refresh').disabled);
  check(await page.locator('#compare-status').innerText()==='已加载保存的记录','comparison controls and status are localized');
  check(errors.length===0,'no unhandled browser errors: '+errors.join('; '));
  await page.close();
  return {fixture:'synthetic paired records; no historical capture modified',checks:checks.length,passed:checks};
}
