// Run with playwright-cli against the dashboard context fixture.
async (page) => {
  const checks=[],errors=[];
  const check=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name);};
  const base=new URL(await page.url()).origin;
  page=await page.context().newPage();
  page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto(base+'/?run=ui-session-graph&lang=en&live=0&detail=raw');
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-session-graph');
  await page.waitForFunction(()=>document.querySelector('#session-count')?.textContent==='4');
  const before=await page.evaluate(()=>({ids:window._lg.nodes.map(n=>n.id),count:window._lensManifest.query.raw_event_count}));
  check(before.count===4,'whole run has all four fixture events');
  const tool=await page.evaluate(()=>window._lg.nodes.find(n=>n.kind==='tool_call').id);
  await page.evaluate(id=>selectNode(id),tool);
  await page.locator('#zoomin').click();
  const original=await page.evaluate(()=>({SEL,ZOOM,FIT,LENS,DETAIL}));
  await page.locator('[data-context-open="conversation"]').first().click();
  await page.waitForSelector('#context-body [data-entry]');
  const wholeEntries=await page.locator('#context-body [data-entry]').count();
  const worker=page.locator('#session-members [data-session-index]').filter({hasText:'codex · worker'});
  await worker.click();
  await page.waitForFunction(()=>window._lensManifest?.query.session_scope?.session_id==='worker');
  check(await page.locator('#session-scope').isVisible(),'visible session scope chip');
  check(await page.locator('#session-scope-count').innerText()==='1 linked tools · 1 linked events','tools deduplicated across sources');
  check(await page.evaluate(()=>window._lensManifest.query.raw_event_count)===1,'graph event count is scoped before aggregation');
  check(!await page.evaluate(()=>window._lg.nodes.some(n=>n.id==='runtime_event/fixture-unassigned'||n.id==='runtime_event/fixture-claude-root'||n.id==='runtime_event/fixture-codex-root')),'shared PID and file do not pull in other sessions');
  check(await page.evaluate(()=>window._lensManifest.derived_edges?.[0]?.confidence)!=null,'derived link confidence retained');
  check(await page.locator('.side [data-whole-run]').isVisible(),'risk panel scope remains explicit');
  check(await page.locator('#timeline-fold [data-whole-run]').innerText()==='Whole run','timeline scope remains explicit');
  await page.locator('[data-context-open="conversation"]').first().click();
  await page.waitForFunction(()=>document.querySelectorAll('#context-body [data-entry]').length===6);
  check(await page.locator('#context-source option').count()===3,'session reader lists only its two sources');
  check(!await page.locator('#context-body').innerText().then(s=>s.includes('Synthetic session graph fixture: claude')||s.includes('Synthetic session graph fixture: codex/root')),'context does not mix another native session');
  await page.evaluate(()=>selectNode('runtime_process/pid/9001'));
  await page.waitForFunction(()=>document.querySelector('#inspection-event-count')?.textContent==='1');
  await page.locator('#inspection-tab-events').click();
  check(await page.locator('#evtbl tbody tr').count()===1,'shared process drilldown intersects the session scope');
  await page.locator('#detailsel').selectOption('summary');
  await page.waitForFunction(()=>window._lensManifest.query.detail==='summary');
  check(await page.evaluate(()=>window._lg.nodes.find(n=>n.id==='overview/tool_calls').data.count)===1,'summary counts recomputed for selected session');
  await page.locator('#session-directory-open').click();
  const item=page.locator('.session-item').filter({has:page.locator('h3').filter({hasText:/^worker/})});
  await item.locator('[data-parent-session]').click();
  check(await page.evaluate(()=>document.activeElement?.id).then(s=>Boolean(s)),'recorded parent link focuses a session entry');
  const parent=page.locator('.session-item').filter({has:page.locator('h3').filter({hasText:/^root codex/})});
  await parent.locator('details > summary').click();
  check(await parent.locator('dl').innerText().then(s=>s.includes('sha256:')),'relation source has immutable evidence reference');
  await parent.locator('[data-view-session]').click();
  await page.waitForFunction(()=>window._lensManifest.query.session_scope?.session_id==='root'&&window._lensManifest.query.session_scope.harness==='codex');
  check(await page.evaluate(()=>window._lensManifest.query.session_scope.event_count)===1,'parent navigation selects codex root, not claude root');
  await page.locator('#session-members [data-session-index]').filter({hasText:'codex · quiet'}).click();
  await page.waitForFunction(()=>window._lensManifest.query.session_scope?.session_id==='quiet');
  await page.locator('#detailsel').selectOption('raw');
  await page.waitForFunction(()=>window._lensManifest.query.detail==='raw');
  check(await page.evaluate(()=>window._lg.nodes.length)===0,'context-only session has empty execution graph');
  check(await page.locator('#loaderror').isHidden(),'empty graph is not a loading failure');
  await worker.click();
  await page.waitForFunction(()=>window._lensManifest.query.session_scope?.session_id==='worker');
  await page.evaluate(()=>loadRun(cur));
  check(await page.evaluate(()=>window._lensManifest.query.session_scope?.session_id)==='worker','refresh retains session');
  await page.locator('[data-investigation="export"]').click();
  check(await page.locator('#investigation-scope').innerText().then(s=>s.includes('codex · worker')),'investigation dialog states the session scope');
  await page.locator('#investigation-close').click();
  await page.screenshot({path:'output/playwright/session-scope-desktop.png'});
  await page.locator('#session-scope-clear').click();
  await page.waitForFunction(()=>!window._lensManifest.query.session_scope);
  check(await page.evaluate(expected=>JSON.stringify({SEL,ZOOM,FIT,LENS,DETAIL})===JSON.stringify(expected),original),'clearing scope restores graph lens, node and zoom');
  check(await page.locator('#context-body [data-entry]').count()===wholeEntries,'clearing scope restores whole-run reading view');
  check(await page.evaluate(()=>window._lensManifest.query.raw_event_count)===4,'clearing scope restores all events');
  await page.locator('#context-fold > summary').click();
  check(!await page.locator('#context-fold').evaluate(el=>el.open),'whole-run conversation closed before switching scope');
  await worker.click();
  await page.waitForFunction(()=>window._lensManifest.query.session_scope?.session_id==='worker');
  await page.locator('#session-scope-clear').click();
  await page.waitForFunction(()=>!window._lensManifest.query.session_scope);
  await page.locator('#context-fold > summary').click();
  await page.waitForSelector('#context-body [data-entry]');
  check(await page.locator('#context-body [data-entry]').count()===wholeEntries,'reopening a restored closed reader renders its cached records');
  await worker.click();
  await page.waitForFunction(()=>window._lensManifest.query.session_scope?.session_id==='worker');
  await page.getByRole('link',{name:'中文',exact:true}).click();
  await page.waitForFunction(()=>window._lensManifest?.query.session_scope?.session_id==='worker');
  check(new URL(await page.url()).searchParams.get('harness')==='codex','language switch preserves namespaced scope');
  check(await page.locator('#session-scope-clear').innerText()==='返回整个 Run','session actions localized');
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile scope has no horizontal overflow');
  await page.screenshot({path:'output/playwright/session-scope-mobile.png'});
  await page.locator('#runsel').selectOption('ui-sessions');
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-sessions');
  check(await page.locator('#session-scope').isHidden(),'changing run clears the previous session scope');
  check(!new URL(await page.url()).searchParams.has('session'),'changing run clears scope URL');
  check(errors.length===0,'no unhandled browser errors: '+errors.join('; '));
  await page.close();
  return {fixture:'synthetic session graph, no real tasks executed',checks:checks.length,passed:checks};
}
