// Run with playwright-cli against the synthetic dashboard context fixture.
async (page) => {
  const checks=[],errors=[];
  const check=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name);};
  const base=new URL(await page.url()).origin;
  page=await page.context().newPage();
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto(base+'/?run=ui-session-graph&harness=codex&session=worker&lang=en&live=0&detail=raw');
  await page.waitForFunction(()=>window._lensManifest?.query.session_scope?.session_id==='worker');
  await page.locator('#zoomin').click();
  const tool=await page.evaluate(()=>window._lg.nodes.find(n=>n.kind==='tool_call').id);
  await page.evaluate(id=>selectNode(id),tool);
  await page.locator('[data-context-open="conversation"]').first().click();
  await page.waitForSelector('#context-body [data-entry]');
  const original=await page.evaluate(()=>({LENS,DETAIL,SEL,ZOOM,FIT,session:SESSION_SCOPE,entries:[...document.querySelectorAll('#context-body [data-entry]')].map(e=>e.dataset.entry)}));
  async function workerRelations(){
    await page.locator('#session-directory-open').click();
    const item=page.locator('.session-item').filter({has:page.locator('h3').filter({hasText:/^worker codex/})});
    const fold=item.locator('.session-relations');
    if(await fold.locator('[data-relations-toggle]').getAttribute('aria-expanded')!=='true')await fold.locator('[data-relations-toggle]').click();
    await fold.locator('.session-relation').first().waitFor();
    return fold;
  }
  let fold=await workerRelations();
  check(await fold.locator('.session-relation').count()===6,'native relationships remain distinct across existing fixture runs');
  check(await fold.locator('.session-relation').filter({has:page.locator('strong').filter({hasText:'Message requested'})}).count()===1,'multiple run occurrences do not multiply a message');
  check(await fold.innerText().then(s=>s.includes('Message requested')&&s.includes('Other run')),'message intent and cross-run destination are explicit');
  const message=fold.locator('.session-relation').filter({has:page.locator('strong').filter({hasText:'Message requested'})});
  await message.locator('details > summary').click();
  check(await message.locator('dl').innerText().then(s=>s.includes('sha256:')&&s.includes('context-')&&s.includes('ui-session-related')),'relationship includes immutable record references');
  await message.locator('[data-open-relation]').click();
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-session-related'&&window._lensManifest.query.session_scope?.session_id==='root');
  check(await page.locator('#runsel').inputValue()==='ui-session-related','related navigation changes run explicitly');
  check(new URL(await page.url()).searchParams.get('run')==='ui-session-related','destination URL reflects run');
  check(await page.locator('#session-related-back').isVisible(),'return action appears');
  await page.locator('#session-related-back').click();
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-session-graph'&&window._lensManifest.query.session_scope?.session_id==='worker');
  await page.locator('#session-related-back').waitFor({state:'hidden'});
  await page.waitForSelector('#context-body [data-entry]');
  check(await page.evaluate(expected=>JSON.stringify({LENS,DETAIL,SEL,ZOOM,FIT,session:SESSION_SCOPE,entries:[...document.querySelectorAll('#context-body [data-entry]')].map(e=>e.dataset.entry)})===JSON.stringify(expected),original),'return restores graph focus, zoom and conversation');
  check(await page.locator('#session-related-back').isHidden(),'return stack is consumed');
  await page.locator('#session-scope-clear').click();
  await page.waitForFunction(()=>!window._lensManifest.query.session_scope);
  fold=await workerRelations();
  await fold.locator('.session-relation').filter({hasText:'Recorded fork'}).locator('[data-open-relation]').click();
  await page.waitForFunction(()=>window._lensManifest?.query.session_scope?.session_id==='branch');
  await page.locator('#session-related-back').click();
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-session-graph'&&!window._lensManifest.query.session_scope);
  await page.locator('#session-related-back').waitFor({state:'hidden'});
  check(await page.locator('#session-scope').isHidden(),'return can restore the full run, not just a session');
  await page.locator('#runsel').selectOption('ui-session-related');
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-session-related');
  await page.locator('#session-directory-open').click();
  const orphan=page.locator('.session-item').filter({has:page.locator('h3').filter({hasText:/^orphan codex/})}).locator('.session-relations');
  await orphan.locator('[data-relations-toggle]').click();
  await orphan.locator('.session-relation').waitFor();
  check(await orphan.innerText().then(s=>s.includes('Target session is not collected or included')),'missing target remains a referenced identity');
  check(await orphan.locator('[data-open-relation]').count()===0,'missing target has no fabricated navigation');
  await page.locator('#session-directory-close').click();
  await page.getByRole('link',{name:'中文',exact:true}).click();
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-session-related');
  await page.locator('#session-directory-open').click();
  const root=page.locator('.session-item').filter({has:page.locator('h3').filter({hasText:/^root codex/})}).locator('.session-relations');
  await root.locator('[data-relations-toggle]').click();
  await root.locator('.session-relation').first().waitFor();
  check(await root.innerText().then(s=>s.includes('同一原生会话的其他运行记录')),'same session across runs has a distinct translated label');
  await root.locator('.session-relation').first().scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/session-relations-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await root.locator('.session-relation').first().scrollIntoViewIfNeeded();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile page has no horizontal overflow');
  check(await page.locator('#session-directory').evaluate(el=>el.scrollWidth<=el.clientWidth+1),'mobile directory has no horizontal overflow');
  await page.screenshot({path:'output/playwright/session-relations-mobile.png'});
  await page.locator('#session-directory-close').click();
  let release,received,block=true;
  const pending=new Promise(resolve=>{release=resolve;}),arrived=new Promise(resolve=>{received=resolve;});
  await page.route('**/api/runs',async route=>{
    if(block){block=false;received();await pending;}
    await route.continue();
  });
  await page.evaluate(()=>{window._pendingRelationNavigation=navigateRelatedSession({run_id:'ui-session-graph',harness:'codex',session_id:'worker',available:true});});
  await arrived;
  await page.locator('#runsel').selectOption('ui-fixture');
  release();
  await page.evaluate(()=>window._pendingRelationNavigation);
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-fixture');
  check(await page.locator('#runsel').inputValue()==='ui-fixture','late relation navigation cannot overwrite a manual run selection');
  check(await page.evaluate(()=>relatedSessionHistory.length)===0,'cancelled navigation does not create a return entry');
  check(errors.length===0,'no unhandled browser errors: '+errors.join('; '));
  await page.close();
  return {fixture:'synthetic native session relationships; no real tasks executed',checks:checks.length,passed:checks};
}
