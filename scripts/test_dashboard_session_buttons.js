// Run with playwright-cli against TestContextDashboardFixture's synthetic store.
async (page) => {
  const checks=[],errors=[];
  const check=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name);};
  const base=new URL(await page.url()).origin;
  page=await page.context().newPage();
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1050});
  let requests=0;
  page.on('request',request=>{if(new URL(request.url()).pathname==='/api/context/session-relations')requests++;});
  await page.goto(base+'/?run=ui-session-graph&harness=codex&session=worker&lang=en&live=0&detail=raw');
  await page.waitForFunction(()=>window._lensManifest?.query.session_scope?.session_id==='worker');
  await page.waitForSelector('[data-relations-toggle]',{state:'attached'});
  const entry=page.getByRole('button',{name:'Related sessions',exact:true}).filter({visible:true});
  check(await entry.count()===1,'overview exposes a named relationship button');
  check(await page.locator('#session-relations-count').isHidden(),'unknown count is not displayed as zero');
  check(requests===0,'rendering the overview does not query every session relationship');
  await page.locator('#zoomin').click();
  const before=await page.evaluate(()=>JSON.stringify({LENS,DETAIL,SEL,ZOOM,FIT,SESSION_SCOPE,graph:window._lg}));
  await entry.click();
  const selected=page.locator('[data-relations-toggle][aria-expanded="true"]');
  await page.locator('.session-relation').first().waitFor();
  check(await selected.count()===1,'overview opens exactly one session relationship list');
  check(await selected.locator('..').locator('..').locator('h3').innerText().then(s=>s.replace(/\s+/g,' ').startsWith('worker codex')),'selected native session is opened');
  check(await selected.locator('[data-relation-count]').innerText()==='6','count describes the loaded relationships');
  check(requests===1,'only the selected session is queried');
  const controls=await selected.getAttribute('aria-controls');
  check(await page.locator('#'+controls).isVisible(),'relationship button controls its visible list');
  check(await page.locator('.session-relation').first().evaluate(el=>{
    const box=el.getBoundingClientRect(),viewport=document.getElementById('session-directory-body').getBoundingClientRect();
    return box.top>=viewport.top&&box.bottom<=viewport.bottom;
  }),'selected relationship is visible without scrolling past other sessions');
  await selected.press('Space');
  check(await page.locator('#'+controls).isHidden(),'Space collapses the relationship list');
  const button=page.locator('[aria-controls="'+controls+'"]');
  await button.press('Enter');
  check(await page.locator('#'+controls).isVisible(),'Enter expands the relationship list');
  check(requests===1,'reopening retains already loaded evidence');
  await page.screenshot({path:'output/playwright/session-buttons-desktop-detail.png'});
  await page.locator('#session-directory-close').click();
  check(await page.evaluate(expected=>JSON.stringify({LENS,DETAIL,SEL,ZOOM,FIT,SESSION_SCOPE,graph:window._lg})===expected,before),'inspecting relationships preserves graph and session');
  check(await page.locator('#session-relations-count').innerText()==='6','selected session count remains visible after closing');
  check(await page.locator('#session-relations-open').evaluate(el=>el===document.activeElement),'closing restores keyboard focus to the entry');
  await page.screenshot({path:'output/playwright/session-buttons-desktop.png'});
  await page.locator('#session-scope-clear').click();
  await page.waitForFunction(()=>!window._lensManifest.query.session_scope);
  check(await page.locator('#session-relations-count').isHidden(),'whole-run button does not mislabel a single-session count');
  await page.locator('#runsel').selectOption('ui-fixture');
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-fixture');
  let fail=true;
  await page.route('**/api/context/session-relations?*',async route=>{
    if(fail){fail=false;await route.fulfill({status:503,body:'fixture relationship query unavailable'});}
    else await route.continue();
  });
  await page.locator('#session-relations-open').click();
  await page.getByRole('button',{name:'Retry',exact:true}).waitFor();
  check(await page.locator('.session-relations').innerText().then(s=>s.includes('Session relationships unavailable')),'query failure has an explicit retry state');
  check(await page.locator('[data-relation-count]').innerText()==='','failed query does not fabricate a count');
  await page.getByRole('button',{name:'Retry',exact:true}).click();
  await page.getByText('No explicit session relationships found in saved records',{exact:true}).waitFor();
  check(await page.locator('[data-relation-count]').innerText()==='0','empty successful query reports zero');
  await page.locator('#session-directory-close').click();
  await page.getByRole('link',{name:'中文',exact:true}).click();
  await page.waitForFunction(()=>window._lensManifest?.run_id==='ui-fixture');
  await page.setViewportSize({width:390,height:844});
  check(await page.getByRole('button',{name:'关联会话',exact:true}).filter({visible:true}).count()===1,'Chinese mobile overview exposes the button');
  check(await page.locator('#runoverview [data-investigation]').count()===3,'all three investigation actions remain');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile overview has no horizontal overflow');
  await page.locator('#session-relations-open').scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/session-buttons-mobile.png'});
  await page.locator('#session-relations-open').click();
  await page.getByText('已保存记录中未找到明确的会话关系',{exact:true}).waitFor();
  check(await page.locator('[data-relations-toggle]').getAttribute('aria-expanded')==='true','mobile relationship button expands the list');
  check(await page.locator('#session-directory').evaluate(el=>el.scrollWidth<=el.clientWidth+1),'mobile relationship dialog has no horizontal overflow');
  await page.screenshot({path:'output/playwright/session-buttons-mobile-detail.png'});
  await page.keyboard.press('Escape');
  check(await page.locator('#session-directory').isHidden(),'Escape returns to the overview');
  check(errors.length===0,'no unhandled browser errors: '+errors.join('; '));
  await page.close();
  return {fixture:'synthetic native sessions; no real agent executed',checks:checks.length,passed:checks};
}
