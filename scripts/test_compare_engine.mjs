import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const env={URLSearchParams,DOMException};
vm.runInNewContext(fs.readFileSync(new URL('../internal/dashboard/compare-engine.js',import.meta.url),'utf8'),env);
const {build,load}=env.AgentRunCompare;
const record=(key,sha,dimension='configuration',extra={})=>({key,dimension,label:key,operation:'recorded_configuration',value:sha?{present:true,sha256:sha}:null,evidence:{id:key},...extra});
const run=records=>({records,complete:true,issues:[]});
let a=run([record('/model','a'),record('/null','null'),record('/plugins','[]'),record('/empty-file','empty','files'),record('open/report','open','files'),record('write/report','write','files'),record('task','task','task')]);
let b=run([record('/model','b'),record('/model','b'),record('/plugins','[]'),record('/new-host','host','network'),record('/empty-file',null,'files'),record('task','task','task')]);
let result=build(a,b),find=key=>result.rows.find(r=>r.key===key);
assert.equal(find('/model').status,'different');
assert.equal(find('/model').b.length,2,'duplicate values retain source references');
assert.equal(find('/plugins').status,'common');
assert.equal(find('/null').status,'only_a','null is a recorded value, not missing');
assert.equal(find('/new-host').status,'only_b','one-sided evidence is not labelled newly executed');
assert.equal(find('/empty-file').status,'unknown','missing body is not an empty file');
assert.equal(result.rows.filter(r=>r.label.endsWith('/report')).length,2,'access and write stay separate');
assert.equal(result.taskRelation,'matching_recorded_tasks');
assert.equal(build(b,a).rows.find(r=>r.key==='/new-host').status,'only_a');
assert.equal(build(run([]),run([])).rows.length,0,'two empty sets do not create an equality claim');
assert.equal(build(run([]),run([])).taskRelation,'task_not_recorded');
assert.equal(build(run([record('task','a','task')]),run([record('task','b','task')])).taskRelation,'different_recorded_tasks');
assert.equal(build({...a,complete:false},b).taskRelation,'task_not_recorded');
assert.equal(build({...a,issues:[{dimension:'configuration',code:'missing'}]},b).rows.find(r=>r.key==='/plugins').status,'unknown');
assert.equal(build(run([record('same','s','files',{partial:true})]),run([record('same','s','files')])).rows[0].status,'unknown');

const pages=Array.from({length:3},(_,n)=>({schema_version:'agentprovenance.comparison_records/v1',run_id:'one',records:[record('r'+n,'v')],issues:[],sources_read:50,has_more:n<2,next_cursor:n<2?String(n+1):''}));
const calls=[];
const get=async(url,{signal}={})=>{
  signal?.throwIfAborted();calls.push(url);
  const u=new URL(url,'http://fixture');
  assert.equal(u.searchParams.has('session'),false,'comparison stays whole-run');
  if(u.pathname==='/api/context/overview')return {coverage:[]};
  return pages[Number(u.searchParams.get('cursor')||0)];
};
const loaded=await load({run:'one',get});
assert.equal(loaded.records.length,3);assert.equal(loaded.sources,150);assert.equal(loaded.complete,true);
assert.equal(calls.length,4);
const abort=new AbortController();abort.abort();
await assert.rejects(load({run:'one',get,signal:abort.signal}),{name:'AbortError'});
await assert.rejects(load({run:'one',get:async url=>url.includes('/overview')?{}:{...pages[0],run_id:'other'}}),/Invalid comparison/);
await assert.rejects(load({run:'one',get:async url=>url.includes('/overview')?{}:pages[0]}),/cursor did not advance/);
await assert.rejects(load({run:'one',get:async()=>{throw new Error('store offline');}}),/store offline/);
const capped=await load({run:'one',get:async url=>url.includes('/overview')?{}:{...pages[0],records:Array.from({length:50001},(_,i)=>record('r'+i,'v'))}});
assert.equal(capped.records.length,50000);assert.equal(capped.complete,false);
assert.equal(capped.issues.at(-1).code,'comparison_record_limit');
assert.equal(build(capped,capped).rows[0].status,'unknown');
console.log('comparison engine: values, absence, duplicate references, tasks, capture gaps, paging, scope, cancellation, failure and bounded memory passed');
