const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const base=process.argv[2],output=path.resolve(process.argv[3]);
(async()=>{
  fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||'chrome',headless:true});
  const reports=[];
  try{
    for(const lang of ['zh-CN','en'])for(const width of [1440,390]){
      const context=await browser.newContext({viewport:{width,height:980},locale:lang,reducedMotion:'reduce'});
      const page=await context.newPage(),errors=[];
      page.on('pageerror',e=>errors.push(e.message));
      const open=async route=>{
        await page.goto(new URL(route,base).href);
        await page.locator('#journey-counts').waitFor();
        await page.waitForFunction(()=>document.querySelector('#journey-counts').dataset.loaded==='true'&&document.querySelector('#dag')?.childElementCount>0);
        if(route.startsWith('current/'))assert.match(await page.locator('#journey-counts').textContent(),/\d/,'current cases retain saved session counts');
        assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'page overflow');
        assert.equal(await page.locator('#journey-more').evaluate(e=>e.open),false);
        assert.equal(await page.locator('.investigation-actions button[data-investigation]').count(),3);
        assert(await page.locator('#journey-capture').isVisible());
        assert(await page.locator('#journey-risk').isVisible());
      };
      await page.goto(new URL('?lang='+lang,base).href);
      await page.locator('.journey-home-start').waitFor();
      assert.equal(await page.locator('[data-case]').count(),4);
      assert.equal(await page.locator('.journey-home-start').count(),1);
      await page.locator(`[data-lang="${lang==='en'?'zh-CN':'en'}"]`).click();
      await page.locator(`[data-lang="${lang}"]`).click();
      assert.equal(await page.locator('.journey-home-start').count(),1);
      await page.screenshot({path:path.join(output,`home-${lang}-${width}.png`),fullPage:true});
      await page.locator('.journey-home-start a').click();
      await page.waitForFunction(()=>document.querySelector('#context-fold')?.open);
      assert.equal(await page.locator('[data-context-tab="conversation"]').getAttribute('aria-selected'),'true');
      await page.locator('#journey-return').click();
      await page.locator('[data-journey="compare"]').click();
      await page.waitForFunction(()=>document.querySelector('#compare-dialog')?.open&&!document.querySelector('#compare-refresh').disabled);
      assert.equal(await page.locator('#compare-a').inputValue(),'run-860466af8a9a');
      assert.equal(await page.locator('#compare-b').inputValue(),'run-3bfc6838a9c6');
      await page.keyboard.press('Escape');
      await open(`current/workspace/${lang}/index.html?live=0`);
      await page.screenshot({path:path.join(output,`workspace-${lang}-${width}.png`)});
      await page.locator('[data-journey="workspace"]').click();
      await page.locator('[data-workspace-entry]').first().waitFor();
      assert.equal(await page.locator('#portable-workspace-tab').getAttribute('aria-selected'),'true');
      const row=page.locator('[data-workspace-entry]').filter({has:page.locator('h3',{hasText:'workspace_bash'})});
      await row.locator('[data-native-body]').click();
      await page.locator('.portable-workspace-result[data-guided]').waitFor();
      assert.equal(await page.locator('#portable-dialog-body>.journey-raw').evaluate(e=>e.open),false);
      await page.screenshot({path:path.join(output,`receipt-${lang}-${width}.png`)});
      await page.keyboard.press('Escape');
      await page.locator('#journey-return').click();
      await page.locator('[data-journey="file"]').click();
      await page.waitForFunction(()=>document.querySelector('#content-body').textContent==='value=2\ncontrolled-write\n');
      assert(await page.locator('#content-body').isVisible());
      await page.screenshot({path:path.join(output,`file-${lang}-${width}.png`)});
      await page.locator('#journey-return').click();
      await page.locator('[data-journey="coverage"]').click();
      assert.equal(await page.locator('[data-context-tab="coverage"]').getAttribute('aria-selected'),'true');
      await page.locator('#journey-return').click();
      await page.locator('[data-journey="delivery"]').click();
      await page.locator('.portable-evidence-dialog[open]').waitFor();
      await page.keyboard.press('Escape');
      await page.locator('#journey-more>summary').click();
      assert.equal(await page.locator('#askgrid .qbtn:visible').count(),13);
      await open(`current/browser/${lang}/index.html?live=0`);
      await page.locator('[data-journey="native"]').click();
      await page.locator('[data-native-entry]').first().waitFor();
      await page.locator('#journey-return').click();
      await page.locator('[data-journey="image"]').click();
      await page.locator('#portable-dialog-body img').waitFor();
      await page.waitForFunction(()=>document.querySelector('#portable-dialog-body img').complete);
      await page.keyboard.press('Escape');
      await open(`${lang}/replay.html?run=run-double-attempt&lens=orchestration&live=0`);
      assert.match(await page.locator('#journey-counts').textContent(),/未保存会话计数|no session counts/);
      await page.locator('[data-journey="calls"]').click();
      await page.waitForFunction(()=>document.querySelector('#inspection')?.textContent.includes('overview/tool_calls')&&document.querySelector('#inspection')?.textContent.includes('tool-d8ae304e37cb'));
      assert(await page.locator('#inspection').isVisible(),'historical calls open saved call evidence');
      await page.locator('#journey-return').click();
      await page.locator('[data-journey="search"]').click();
      await page.locator('#search-dialog[open]').waitFor();
      await page.keyboard.press('Escape');
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
      assert.deepEqual(errors,[]);
      reports.push({lang,width,passed:true,pairedComparison:true,originalFile:true,originalScreenshot:true,advancedViews:13,errors});
      await context.close();
    }
  }finally{await browser.close();fs.writeFileSync(path.join(output,'report.json'),JSON.stringify({reports},null,2)+'\n');}
  console.log(JSON.stringify({reports}));
})().catch(error=>{console.error(error);process.exitCode=1});
